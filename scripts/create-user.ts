import 'dotenv/config';
import * as crypto from 'crypto';
import * as readline from 'readline/promises';
import { stdin as input, stdout as output } from 'process';
import { PrismaPg } from '@prisma/adapter-pg';
import { PrismaClient } from '../src/generated/prisma/client';
import { HashService } from '../src/auth/hash.service';

// Connect using DIRECT_URL (for Neon direct access) or fallback to DATABASE_URL
const connectionString =
  process.env.DIRECT_URL || process.env.DATABASE_URL;

if (!connectionString) {
  console.error('❌ Error: Neither DIRECT_URL nor DATABASE_URL is defined in environment.');
  process.exit(1);
}

const adapter = new PrismaPg({ connectionString });
const prisma = new PrismaClient({ adapter });
const hashService = new HashService();

interface ParsedArgs {
  email?: string;
  username?: string;
  password?: string;
  isAdmin?: boolean;
}

function parseCliArgs(): ParsedArgs {
  const args = process.argv.slice(2);
  const parsed: ParsedArgs = {};

  for (let i = 0; i < args.length; i++) {
    const arg = args[i];
    if (arg === '--email' || arg === '-e') {
      parsed.email = args[++i];
    } else if (arg === '--username' || arg === '-u' || arg === '--name') {
      parsed.username = args[++i];
    } else if (arg === '--password' || arg === '-p') {
      parsed.password = args[++i];
    } else if (arg === '--admin') {
      parsed.isAdmin = true;
    }
  }

  return parsed;
}

function generateRandomPassword(length = 12): string {
  const charset = 'ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnpqrstuvwxyz23456789';
  let password = '';
  for (let i = 0; i < length; i++) {
    password += charset.charAt(crypto.randomInt(0, charset.length));
  }
  return password;
}

function isValidEmail(email: string): boolean {
  return /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email);
}

async function main() {
  console.log('\n=========================================');
  console.log('   SPK-GIS — Create User CLI Utility     ');
  console.log('=========================================\n');

  const cliArgs = parseCliArgs();
  const rl = readline.createInterface({ input, output });

  try {
    let email = cliArgs.email?.trim();
    while (!email || !isValidEmail(email)) {
      if (email && !isValidEmail(email)) {
        console.log('⚠️  Invalid email format. Please try again.');
      }
      email = (await rl.question('📧 Enter user email: ')).trim();
    }

    // Check if email already exists
    const existingByEmail = await prisma.user.findUnique({
      where: { email },
    });
    if (existingByEmail) {
      console.error(`\n❌ Error: User with email "${email}" already exists.`);
      process.exit(1);
    }

    let username = cliArgs.username?.trim();
    while (!username) {
      username = (await rl.question('👤 Enter username: ')).trim();
    }

    // Check if username already exists
    const existingByName = await prisma.user.findUnique({
      where: { name: username },
    });
    if (existingByName) {
      console.error(`\n❌ Error: User with username "${username}" already exists.`);
      process.exit(1);
    }

    let password = cliArgs.password?.trim();
    let isAutoGenerated = false;

    if (!password) {
      const inputPass = (
        await rl.question(
          '🔑 Enter initial password (leave blank to auto-generate): ',
        )
      ).trim();

      if (inputPass) {
        password = inputPass;
      } else {
        password = generateRandomPassword(12);
        isAutoGenerated = true;
      }
    }

    if (password.length < 6) {
      console.error('\n❌ Error: Password must be at least 6 characters long.');
      process.exit(1);
    }

    let isAdmin = cliArgs.isAdmin;
    if (isAdmin === undefined) {
      const adminAnswer = (
        await rl.question('🛡️  Grant administrator privileges? (y/N): ')
      )
        .trim()
        .toLowerCase();
      isAdmin = adminAnswer === 'y' || adminAnswer === 'yes';
    }

    console.log('\nCreating user in database...');
    const hashedPassword = await hashService.hash(password);

    const newUser = await prisma.user.create({
      data: {
        name: username,
        email,
        password: hashedPassword,
        isAdmin,
        mustChangePassword: true, // Always required to change password on first login
      },
    });

    console.log('\n✅ User created successfully!');
    console.log('-----------------------------------------');
    console.log(`🆔 ID                   : ${newUser.id}`);
    console.log(`👤 Username             : ${newUser.name}`);
    console.log(`📧 Email                : ${newUser.email}`);
    console.log(`🛡️  Role                 : ${newUser.isAdmin ? 'Admin' : 'User'}`);
    console.log(`🔑 Initial Password     : ${password}${isAutoGenerated ? ' (Auto-generated)' : ''}`);
    console.log(`⚠️  Must Change Password : YES (Enforced upon first login)`);
    console.log('-----------------------------------------\n');
  } catch (error) {
    console.error('\n❌ Unexpected error creating user:', error);
    process.exit(1);
  } finally {
    rl.close();
    await prisma.$disconnect();
  }
}

main();
